/*Displaying a nested if-else statement with unary operators */

#include <stdio.h>

int main() {
    int a = 5, b = 10;

    if (a > b) {
        printf("a is greater than b\n");
    } else if (a < b) {
        printf("a is less than b\n");
    } else {
        printf("a is equal to b\n");
    }

    return 0;
}

