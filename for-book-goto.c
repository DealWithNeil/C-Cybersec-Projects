/*Give an example for this and print it: char ch;
ch = 'a';   
ch = 'A';   
ch = '0';   
ch = ' ';   
*/
#include <stdio.h>

int main(void)
{
    char ch;
    ch = 'a';
    printf("ch = %c\n", ch);
    ch = 'A';
    printf("ch = %c\n", ch);
    ch = '0';
    printf("ch = %c\n", ch);
    ch = ' ';
    printf("ch = %c\n", ch);
    

    return 0;
}
